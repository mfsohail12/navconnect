export type Dictionary = typeof en & { rtl?: boolean };

export const LANGS: readonly LangCode[] = ["en", "fr", "ar", "zh"];

export const I: Record<LangCode, Dictionary> = { en, fr, ar, zh };

export function isLangCode(value: unknown): value is LangCode {
  return typeof value === "string" && (LANGS as readonly string[]).includes(value);
}

/** Replace {key} placeholders. Missing values become empty strings, as in the prototype. */
export function fill(
  template: string,
  values: Record<string, string | number | null | undefined>,
): string {
  return template.replace(/\{(\w+)\}/g, (_, k: string) =>
    values[k] != null ? String(values[k]) : "",
  );
}

/** The spoken and written instruction for one route step. */
export function instr(step: Step, dest: DestId, lang: LangCode): string {
  const L = I[lang];
  const lm = L.lm as Record<string, string>;
  const el = L.el as Record<string, string>;
  const sides = L.sides as Record<string, string>;
  return fill(L.a[step.a], {
    lm: step.lm ? lm[step.lm] : "",
    el: step.el ? el[step.el] : "",
    f: step.f ?? "",
    dest: L.dest[dest],
    side: step.side ? sides[step.side] : "",
  });
}

/** Floor label for a step header or the nav screen, e.g. "Main floor" or "Floor 7". */
export function floorLabel(floor: string | number, lang: LangCode): string {
  const L = I[lang];
  return floor === "main" ? L.mainFl : `${L.floor} ${floor}`;
}

